export const getCities = () => Object.keys(BUS_ROUTES);

export const getCityRoutes = (city) =>
  BUS_ROUTES[city]?.routes || [];

export const getActiveRoutes = (city) =>
  getCityRoutes(city).filter(r => r.active);

export const getAllRoutes = () =>
  Object.values(BUS_ROUTES).flatMap(c => c.routes);

export const getRouteById = (id) =>
  getAllRoutes().find(r => r.id === id);

export const getBRTRoutes = () =>
  getAllRoutes().filter(r => r.brt);

export const getIntercityRoutes = () =>
  getAllRoutes().filter(r => r.intercity);

